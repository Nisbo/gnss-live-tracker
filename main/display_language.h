static inline const char *display_weekday(unsigned language,unsigned day) {
    static const char *const days[7][2]={{"So","Sun"},{"Mo","Mon"},{"Di","Tue"},{"Mi","Wed"},{"Do","Thu"},{"Fr","Fri"},{"Sa","Sat"}};
    return day<7?days[day][language==1]:"";
}
static inline const char *display_month(unsigned month) {
    static const char *const months[]={"Jan","Feb","Mar","Apr","May","Jun","Jul","Aug","Sep","Oct","Nov","Dec"};
    return month<12?months[month]:"";
}
