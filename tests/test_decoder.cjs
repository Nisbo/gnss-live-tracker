const fs = require('fs');
const vm = require('vm');
const assert = require('assert');
const cp = require('child_process');
const path = require('path');
const context = {};
vm.createContext(context);
vm.runInContext(fs.readFileSync(path.join(__dirname, '../main/web/ttn-position-decoder.js'), 'utf8'), context);
const decode = (hex, fPort = 10) => context.decodeUplink({fPort, bytes: [...Buffer.from(hex, 'hex')]});
const hex = cp.execFileSync(process.argv[2] || require('path').join(process.env.TRACKER_TEST_TMP||require('os').tmpdir(),'tracker-gnss-test'), {encoding:'utf8'}).split('\n')[0];
let d = decode(hex).data;
assert.strictEqual(d.latitude, -33.9);
assert.strictEqual(d.longitude, -70.6);
assert.strictEqual(d.altitude, -12);
assert.strictEqual(d.galileo_visible, 2);
assert.strictEqual(d.galileo_used, true);
assert.strictEqual(d.hdop, 0.85);
assert.strictEqual(d.simulated, false);
const b = Buffer.from(hex, 'hex');
b[1] &= ~2;
d = decode(b.toString('hex')).data;
assert.strictEqual(d.latitude, null);
assert.strictEqual(d.longitude, null);
assert.strictEqual(d.altitude, null);
assert.strictEqual(decode('01011cbabc8006c1545201f40000').data.simulated, true);
let sat = decode('01000201010101e3000142', 11).data;
assert.strictEqual(sat.satellites[0].system, 'Galileo');
assert.strictEqual(sat.satellites[0].nmea_id, 1);
assert.strictEqual(sat.satellites[0].used_in_fix, true);
assert.strictEqual(sat.satellites[0].cn0_db_hz, 66);
sat = decode('01000201010101430001ff', 11).data;
assert.strictEqual(sat.satellites[0].used_in_fix, null);
assert.strictEqual(sat.satellites[0].cn0_db_hz, null);
assert(decode('0101').errors);
assert(decode('01000100010000', 11).errors);
console.log('TTN decoder: C-encoded position, v1 compatibility, no-fix, Galileo, unknown fields and malformed input: PASS');
